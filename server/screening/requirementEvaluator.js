
const {
  generateStructuredOutput
} = require('../services/llmService');

const {
  evaluationSchema,
  validateEvaluation
} = require('../schemas/evaluationSchema');

async function evaluateRequirements(jobData, resumeData) {
  if (
    !jobData ||
    !Array.isArray(jobData.requirements)
  ) {
    throw new Error('Invalid job description analysis.');
  }

  if (
    !resumeData ||
    !Array.isArray(resumeData.skills) ||
    !Array.isArray(resumeData.work_experience) ||
    !Array.isArray(resumeData.internships) ||
    !Array.isArray(resumeData.projects) ||
    !Array.isArray(resumeData.education)
  ) {
    throw new Error('Invalid structured resume data.');
  }

  const prompt = `
You are evaluating a candidate against a job description.

Evaluate EVERY job requirement individually using only the
supplied structured resume data.

JOB TITLE:
${jobData.job_title}

JOB REQUIREMENTS:
${JSON.stringify(jobData.requirements, null, 2)}

STRUCTURED RESUME:
${JSON.stringify(resumeData, null, 2)}

STATUS RULES:

1. MET:
   The resume contains clear and relevant evidence that satisfies
   the requirement.

2. PARTIAL:
   The resume contains some relevant evidence, but it does not
   fully satisfy the requirement.

3. MISSING:
   No relevant supporting evidence exists in the resume.

EVIDENCE RULES:

1. Every MET or PARTIAL evaluation must contain at least one
   supporting evidence quote.

2. Every evidence_quote MUST be an exact, continuous text
   substring taken from the VALUE of a field in the structured
   resume.

3. Never copy JSON property names, keys, field labels, quotation
   marks, braces, commas, or JSON fragments into evidence_quote.

4. For example, if the resume contains:

   {
     "qualification": "Bachelor of Technology",
     "field_of_study": "Computer Science"
   }

   Valid evidence quotes include:
   "Bachelor of Technology"
   "Computer Science"

   Invalid evidence quotes include:
   "field_of_study: Computer Science"
   "\\"field_of_study\\":\\"Computer Science\\""
   "qualification: Bachelor of Technology"

5. Evidence must be copied from actual resume content, not
   generated by combining separate fields or paraphrasing them.

6. Use the correct source_section:
   skills, work_experience, internships, projects or education.

7. Evidence must genuinely support the requirement.

8. Multiple evidence entries may be used when different resume
   sections support the same requirement.

9. A skill appearing in the skills section proves that the
   candidate lists that skill. It does not automatically prove
   professional experience.

10. Do not invent candidate information or supporting evidence.

11. For MISSING evaluations, return an empty evidence array.

12. Keep evidence quotes concise. Prefer the smallest exact
    phrase that demonstrates the relevant information.

EXPERIENCE RULES:

1. Academic and personal projects must not be treated as
   professional employment.

2. Training internships must remain distinguishable from
   professional employment.

3. Do not calculate years of experience.

4. For requirements involving professional experience, identify
   relevant work_experience records using their zero-based
   array indices.

5. Identify relevant internship records separately using their
   zero-based array indices.

6. Do not invent or estimate employment dates.

7. If the JD explicitly requires minimum years of experience,
   do not mark the requirement MET merely because the candidate
   has relevant skills or a short period of employment.

8. When available dates or evidence are insufficient to
   establish the required duration, use PARTIAL if relevant
   evidence exists.

9. Do not use academic projects or training internships to
   satisfy professional employment duration.

GENERAL RULES:

1. Evaluate all requirement IDs exactly once.

2. Preserve every requirement_id from the job description.

3. Do not create new requirement IDs.

4. Return empty relevant_work_experience_indices and
   relevant_internship_indices when no records are relevant.

5. Do not return scores or percentages.

6. Do not return markdown.

7. Return JSON only, following the supplied schema.

OUTPUT STRUCTURE:

{
  "evaluations": [
    {
      "requirement_id": "R1",
      "status": "MET",
      "evidence": [
        {
          "source_section": "work_experience",
          "evidence_quote": "Exact text from a resume field value"
        }
      ],
      "relevant_work_experience_indices": [0],
      "relevant_internship_indices": [],
      "explanation": "Brief explanation of the decision."
    }
  ]
}
`;

  return generateStructuredOutput({
    prompt,
    schema: evaluationSchema,
    schemaName: 'Requirement Evaluator',
    validate: data =>
      validateEvaluation(
        data,
        jobData.requirements,
        resumeData
      )
  });
}

module.exports = {
  evaluateRequirements
};
